function slugify(value: string) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

const RETAILERS: Record<string, { name: string; base: string }> = {
  Myntra: { name: "Myntra", base: "https://www.myntra.com" },
  Ajio: { name: "AJIO", base: "https://www.ajio.com/search/?text=" },
  Amazon: { name: "Amazon India", base: "https://www.amazon.in/s?k=" },
};

function buildAffiliateUrl(product: Omit<Product, "affiliateUrl" | "retailer">, retailer: keyof typeof RETAILERS) {
  const query = encodeURIComponent(product.name);
  const tracked = `utm_source=wearwise&utm_medium=affiliate&utm_campaign=${product.slug}`;
  if (retailer === "Myntra") {
    return `https://www.myntra.com/${CATEGORY_PATH[product.category] ?? "shop"}?rawQuery=${query}&${tracked}`;
  }
  if (retailer === "Ajio") {
    return `https://www.ajio.com/search/?text=${query}&${tracked}`;
  }
  return `https://www.amazon.in/s?k=${query}&tag=wearwise-21&${tracked}`;
}

const RETAILER_CYCLE: (keyof typeof RETAILERS)[] = ["Myntra", "Ajio", "Amazon"];

export const PRODUCTS: Product[] = seeds.map((seed, index) => {
  const retailerKey = RETAILER_CYCLE[index % RETAILER_CYCLE.length];
  const base = {
    ...seed,
    slug: seed.slug || slugify(seed.name),
    id: `p${String(index + 1).padStart(3, "0")}`,
    seasons: seed.seasons ?? ["All-season"],
    fit: seed.fit ?? "regular",
    sizes: seed.sizes ?? APPAREL,
    gallery: seed.gallery ?? [seed.image],
    specs: seed.specs ?? [],
    stock: seed.stock ?? 12 + ((index * 7) % 30),
    sponsored: seed.sponsored ?? false,
  } satisfies Omit<Product, "affiliateUrl" | "retailer">;

  return {
    ...base,
    retailer: RETAILERS[retailerKey].name,
    affiliateUrl: buildAffiliateUrl(base, retailerKey),
  };
});

